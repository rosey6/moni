from pathlib import Path
from playwright.sync_api import sync_playwright

output = Path('artifacts/subscriptions')
output.mkdir(parents=True, exist_ok=True)

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    for width in (375, 390, 768, 1024, 1440):
        page = browser.new_page(viewport={'width': width, 'height': 900})
        page.route('**/onboarding.php', lambda route: route.fulfill(status=200, content_type='application/json', body='{"data":{"state":{"onboardingCompleted":true}}}'))
        page.goto('http://127.0.0.1:4173/#unexpected', wait_until='networkidle')
        page.get_by_role('button', name='Passer cette étape').click()
        page.get_by_role('button', name='Continuer').click()
        assert page.url.endswith('#subscriptions')
        assert page.locator('.subscription-card').count() == 8
        page.get_by_role('button', name='Revenir à l’étape précédente').click()
        assert page.url.endswith('#unexpected')
        page.get_by_role('button', name='Continuer').click()
        page.screenshot(path=output / f'selection-{width}.png', full_page=True)
        page.get_by_role('button', name='Configurer Spotify').click()
        assert page.url.endswith('#subscription-edit')
        assert not page.get_by_label('Montant mensuel (XOF)').is_visible()
        page.get_by_role('button', name='Revenir à l’étape précédente').click()
        assert page.url.endswith('#subscriptions')
        page.get_by_role('button', name='Configurer Spotify').click()
        page.get_by_role('button', name='Retour').click()
        assert page.url.endswith('#subscriptions')
        page.get_by_role('button', name='Configurer Spotify').click()
        page.locator('.calendar-day').filter(has_text='15').click()
        page.get_by_label('Montant mensuel (XOF)').fill('5000')
        page.screenshot(path=output / f'calendrier-{width}.png', full_page=True)
        page.get_by_role('button', name='Valider le montant').click()
        page.get_by_role('button', name='Enregistrer').click()
        assert page.get_by_role('button', name='Retirer Spotify').is_visible()
        page.screenshot(path=output / f'selectionne-{width}.png', full_page=True)
        page.get_by_role('button', name='Modifier Spotify').click()
        page.locator('.calendar-day').filter(has_text='15').click()
        page.get_by_label('Montant mensuel (XOF)').fill('6000')
        page.get_by_role('button', name='Valider le montant').click()
        page.get_by_role('button', name='Enregistrer').click()
        page.get_by_role('button', name='Retirer Spotify').click()
        assert page.get_by_role('button', name='Configurer Spotify').is_visible()
        page.get_by_role('button', name='Continuer').click()
        page.screenshot(path=output / f'chargement-{width}.png', full_page=True)
        page.wait_for_url('**/#dashboard')
        assert page.get_by_role('heading', name='Vue d’ensemble').is_visible()
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        page.close()
    browser.close()
print('SUBSCRIPTIONS_PLAYWRIGHT_PASS')
